target_file = 'packages/shared/src/data/mockFloodData.ts'
with open(target_file, 'r', encoding='utf-8') as f:
    content = f.read()

# Update totalLandAreaKm2 in DEMO_MUNICIPALITY
content = re.sub(r'totalLandAreaKm2:\s*[0-9\.]+', 'totalLandAreaKm2: 83.59', content)

# Process each barangay in specs
updated_count = 0
for zid, spec in specs.items():
    pat = r'(id:\s*\'' + re.escape(zid) + r'\'[\s\S]*?poly:\s*\[[\s\S]*?\n\s*\]\,)'
    m = re.search(pat, content)
    if not m:
        print(f'Warning: {zid} not found!')
        continue
    
    block = m.group(1)
    
    # Replace pop
    block = re.sub(r'pop:\s*[0-9]+', f'pop: {spec["pop"]}', block)
    # Replace areaKm2
    block = re.sub(r'areaKm2:\s*[0-9\.]+', f'areaKm2: {spec["areaKm2"]}', block)
    # Replace center
    c_str = f'center: [{spec["center"][0]:.4f}, {spec["center"][1]:.4f}]'
    block = re.sub(r'center:\s*\[[0-9\.\s,]+\]', c_str, block)
    # Replace poly
    poly_lines = ['poly: [']
    for pt in spec['poly']:
        poly_lines.append(f'      [{pt[0]:.4f}, {pt[1]:.4f}],')
    poly_lines.append('    ],')
    poly_str = '\n'.join(poly_lines)
    block = re.sub(r'poly:\s*\[[\s\S]*?\n\s*\]\,', poly_str, block)
    
    content = content[:m.start(1)] + block + content[m.end(1):]
    updated_count += 1

with open(target_file, 'w', encoding='utf-8') as f:
    f.write(content)

print(f'Successfully updated {updated_count}/33 barangays in mockFloodData.ts!')
